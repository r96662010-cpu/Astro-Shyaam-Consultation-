    fun getRandomCards(count: Int): List<Pair<TarotCard, Boolean>> {
        val shuffled = majorArcana.shuffled()
        return shuffled.take(count).map { card ->
            val isReversed = kotlin.random.Random.nextBoolean()
            card to isReversed
        }
    }
